function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')
    .trim()
    .substring(0, 80);
}

async function main() {
  console.log('🌱 Seeding database...');

  // Clear existing data
  await prisma.statusLog.deleteMany();
  await prisma.comment.deleteMany();
  await prisma.attachment.deleteMany();
  await prisma.signal.deleteMany();
  await prisma.signalType.deleteMany();
  await prisma.category.deleteMany();
  await prisma.user.deleteMany();

  // Seed categories and types
  for (let i = 0; i < categoriesData.length; i++) {
    const cat = categoriesData[i];
    const category = await prisma.category.create({
      data: {
        name: cat.name,
        slug: cat.slug,
        icon: cat.icon,
        orderNum: i,
      },
    });

    for (let j = 0; j < cat.types.length; j++) {
      const typeName = cat.types[j];
      await prisma.signalType.create({
        data: {
          name: typeName,
          slug: `${cat.slug}-${slugify(typeName)}-${j}`,
          categoryId: category.id,
          orderNum: j,
        },
      });
    }

    console.log(`  ✅ ${cat.icon} ${cat.name} (${cat.types.length} типа)`);
  }

  // Create admin user
  const bcrypt = await import('bcryptjs');
  const hashedPassword = await bcrypt.hash('admin123', 10);

  await prisma.user.create({
    data: {
      name: 'Администратор',
      email: 'admin@pernik.bg',
      password: hashedPassword,
      role: 'admin',
    },
  });

  console.log('  ✅ 👤 Администратор (admin@pernik.bg / admin123)');
  console.log('\n✨ Seed completed!');
}

main()
  .catch((e) => {
    console.error('❌ Seed failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
